package io.github.seayar.modbus4j.net;

import io.github.seayar.modbus4j.codec.ModbusCodec;
import io.github.seayar.modbus4j.codec.ModbusFrame;
import io.netty.channel.ChannelHandlerContext;
import io.netty.channel.socket.DatagramPacket;
import io.netty.handler.codec.MessageToMessageDecoder;

import java.util.List;

public class DatagramFrameDecoder extends MessageToMessageDecoder<DatagramPacket> {
    private final ModbusCodec codec;

    public DatagramFrameDecoder(ModbusCodec codec) {
        this.codec = codec;
    }

    @Override
    protected void decode(ChannelHandlerContext ctx, DatagramPacket packet, List<Object> out) throws Exception {
        ModbusFrame frame = codec.decode(packet.content());
        if (frame != null)
            out.add(frame);
    }
}
